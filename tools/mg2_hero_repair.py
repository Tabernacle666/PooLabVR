#!/usr/bin/env python3
"""Validate all MG2 GLBs and restore 4 hero meshes from exact ASCII sources.

Git-stored hero GLBs previously acquired additional bytes during an unsafe
binary upload. Their trusted original generated bytes are stored as strict
base64 text in hero_sources. Decoding takes place only in the untracked
.oasis-local build staging area; source GLBs and downloaded CC0 maps in
the repository checkout are never modified.
"""
import base64
import hashlib
import json
from pathlib import Path
import struct
import sys
import tempfile
import os

ROOT = Path(__file__).resolve().parents[1]
HERO_SOURCES = ROOT / "assets" / "packs" / "oasis_mg2_v1" / "hero_sources"
HERO = {
    "fire_extinguisher01": (665876, 10632),
    "light_panel01": (88528, 1764),
    "door_office_solid01": (636960, 4012),
    "desk_office01": (734756, 3740),
}


def git_sha(data):
    return hashlib.sha1(b"blob " + str(len(data)).encode("ascii") +
                        b"\0" + data).hexdigest()


def inspect_glb(data):
    if len(data) < 28:
        raise ValueError("truncated GLB")
    magic, version, declared = struct.unpack_from("<III", data, 0)
    if (magic, version, declared) != (0x46546C67, 2, len(data)):
        raise ValueError(f"GLB header mismatch, actual={len(data)}, declared={declared}")
    offset = 12
    chunks = []
    for expected in (0x4E4F534A, 0x004E4942):
        if offset + 8 > len(data):
            raise ValueError("missing GLB chunk header")
        length, kind = struct.unpack_from("<II", data, offset)
        offset += 8
        if kind != expected or length % 4 or offset + length > len(data):
            raise ValueError("invalid GLB chunk boundaries")
        chunks.append(data[offset:offset + length])
        offset += length
    if offset != len(data):
        raise ValueError("unexpected bytes after GLB binary chunk")
    document = json.loads(chunks[0].decode("utf-8").strip())
    if document.get("asset", {}).get("version") != "2.0":
        raise ValueError("invalid glTF 2.0 asset")
    triangle_count = 0
    for mesh in document.get("meshes", []):
        for primitive in mesh.get("primitives", []):
            index = primitive["indices"]
            count = document["accessors"][index]["count"]
            if count % 3:
                raise ValueError("nontriangular GLB mesh indices")
            triangle_count += count // 3
    if triangle_count == 0:
        raise ValueError("empty mesh")
    return document, triangle_count


def write_json(path, data):
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", newline="\n", suffix=".tmp",
        dir=path.parent, delete=False
    ) as file:
        json.dump(data, file, indent=2, ensure_ascii=False)
        file.write("\n")
        temp = file.name
    os.replace(temp, path)


def main(pack_root):
    pack_root = Path(pack_root).resolve()
    tracked_root = ROOT / "assets" / "packs" / "oasis_mg2_v1"
    if pack_root == tracked_root or tracked_root in pack_root.parents:
        raise ValueError("Refusing to write repaired assets into tracked Git source")
    path = pack_root / "pack.json"
    pack = json.loads(path.read_text(encoding="utf-8"))
    changed = False
    repaired = []
    for row in pack["assets"]:
        item = pack_root / row["glb"]
        raw = item.read_bytes()
        name = item.stem
        try:
            document, triangles = inspect_glb(raw)
        except (ValueError, KeyError, UnicodeError, json.JSONDecodeError) as original:
            if name not in HERO:
                raise ValueError(f"MG2 invalid GLB {row['asset_key']} ({item}): {original}") from original
            source = HERO_SOURCES / (name + ".glb.b64")
            if not source.is_file():
                raise ValueError(f"MG2 missing authoring source {source}") from original
            rebuilt = base64.b64decode(source.read_bytes(), validate=True)
            expected_size, expected_triangles = HERO[name]
            document, triangles = inspect_glb(rebuilt)
            if len(rebuilt) != expected_size or triangles != expected_triangles:
                raise ValueError("MG2 hero original mismatch: " + name) from original
            # Only update the runtime pack. Keep the older Git tracked source
            # intact to avoid regeneration conflicts with other developers.
            with tempfile.NamedTemporaryFile(
                dir=item.parent, suffix=".tmp", delete=False
            ) as file:
                file.write(rebuilt)
                temp = file.name
            os.replace(temp, item)
            raw = rebuilt
            row["git_blob_sha1"] = git_sha(rebuilt)
            meta_path = pack_root / row["metadata"]
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
            meta["geometry"].update({
                "triangles": triangles,
                "bytes": len(rebuilt),
                "embedded_textures": len(document.get("images", [])),
                "material_slots": len(document.get("materials", [])),
            })
            write_json(meta_path, meta)
            provenance_path = pack_root / row["provenance"]
            provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
            if "hero_geometry_git_blob_sha1" in provenance:
                provenance["hero_geometry_git_blob_sha1"] = git_sha(rebuilt)
                write_json(provenance_path, provenance)
            repaired.append(name)
            changed = True
        # Verify both GLB and pack content agree after optional repair.
        declared_sha = row.get("git_blob_sha1")
        actual_sha = git_sha(raw)
        if declared_sha != actual_sha:
            raise ValueError(f"MG2 SHA mismatch: {row['asset_key']}")
        meta = json.loads((pack_root / row["metadata"]).read_text(encoding="utf-8"))
        if meta.get("asset_revision") != row["asset_revision"]:
            raise ValueError(f"MG2 revision mismatch: {row['asset_key']}")
        if meta["geometry"]["triangles"] != triangles or meta["geometry"]["bytes"] != len(raw):
            raise ValueError(f"MG2 metadata mismatch: {row['asset_key']}")
    if changed:
        write_json(path, pack)
    print(f"[MG2] {len(pack['assets'])} GLBs verified, {len(repaired)} hero binaries repaired locally")
    if repaired:
        print("[MG2] Restored: " + ", ".join(repaired))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: python tools/mg2_hero_repair.py PACK_DIRECTORY")
    main(sys.argv[1])
